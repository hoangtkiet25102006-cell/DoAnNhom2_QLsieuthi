CREATE TABLE IF NOT EXISTS khach_hang (
    ma_kh INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ho_ten VARCHAR(150) NOT NULL,
    so_dien_thoai VARCHAR(15)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_khach_hang_so_dien_thoai
    ON khach_hang(so_dien_thoai)
    WHERE so_dien_thoai IS NOT NULL;

CREATE TABLE IF NOT EXISTS the_vip (
    ma_kh INTEGER REFERENCES khach_hang(ma_kh),
    ma_the VARCHAR(10) PRIMARY KEY,
    ti_le_giam NUMERIC(12, 0),
    so_lan_toi_da INTEGER NOT NULL,
    so_lan_con_lai INTEGER NOT NULL,
    trang_thai VARCHAR(30)
);

