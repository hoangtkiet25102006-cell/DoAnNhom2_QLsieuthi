CREATE TABLE IF NOT EXISTS don_hang (
    ma_don_hang INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_khach_hang VARCHAR(150) NOT NULL,
    ma_kh INTEGER REFERENCES khach_hang(ma_kh),
    ma_the VARCHAR(10) REFERENCES the_vip(ma_the),
    tien_hang BIGINT NOT NULL CHECK (tien_hang >= 0),
    giam_gia BIGINT NOT NULL DEFAULT 0
        CONSTRAINT ck_don_hang_giam_gia CHECK (giam_gia >= 0 AND giam_gia <= tien_hang),
    giam_gia_thu_cong BIGINT NOT NULL DEFAULT 0 CHECK (giam_gia_thu_cong >= 0),
    giam_gia_vip BIGINT NOT NULL DEFAULT 0 CHECK (giam_gia_vip >= 0),
    ty_le_giam_vip NUMERIC(5, 2) NOT NULL DEFAULT 0 CHECK (ty_le_giam_vip BETWEEN 0 AND 100),
    tong_tien BIGINT NOT NULL CHECK (tong_tien >= 0),
    tien_khach_dua BIGINT NOT NULL CHECK (tien_khach_dua >= tong_tien),
    tien_thua BIGINT NOT NULL CHECK (tien_thua >= 0),
    phuong_thuc_thanh_toan VARCHAR(30) NOT NULL,
    thoi_gian_tao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

