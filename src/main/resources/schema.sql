CREATE TABLE IF NOT EXISTS tai_khoan (
    ten_dang_nhap VARCHAR(60) PRIMARY KEY,
    mat_khau_ma_hoa VARCHAR(100) NOT NULL,
    ho_ten VARCHAR(150) NOT NULL,
    vai_tro VARCHAR(20) NOT NULL CHECK (vai_tro IN ('MANAGER', 'EMPLOYEE')),
